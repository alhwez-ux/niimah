export function districtsOf(city) {
  return ASIR_DISTRICTS[city] || [];
}

export function initialLocation(source = {}) {
  const city = ASIR_CITIES.includes(source.city) ? source.city : DEFAULT_CITY;
  const list = districtsOf(city);
  const saved = typeof source.district === 'string' ? source.district.trim() : '';
  if (saved && list.includes(saved)) {
    return { city, districtChoice: saved, customDistrict: '' };
  }
  if (saved) return { city, districtChoice: CUSTOM_DISTRICT, customDistrict: saved };
  return { city, districtChoice: list[0] || CUSTOM_DISTRICT, customDistrict: '' };
}

export function readLocation(city, districtChoice, customDistrict) {
  const safeCity = ASIR_CITIES.includes(city) ? city : DEFAULT_CITY;
  const district = districtChoice === CUSTOM_DISTRICT ? (customDistrict || '').trim() : districtChoice;
  if (!district) return null;
  return { city: safeCity, district };
}
